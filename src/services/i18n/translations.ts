/**
 * Indic Indian Numbering System Formatter (Lakhs & Crores)
 * e.g., 37,12,450 Cr -> formatted with proper localized language labels
 */
export function formatIndicCurrency(
  crores: number,
  lang: LanguageCode = 'en'
): string {
  if (crores == null || isNaN(crores)) return '₹ 0';

  if (lang === 'hi') {
    if (crores >= 100000) {
      const lakhCrores = (crores / 100000).toFixed(2);
      return `₹ ${lakhCrores} लाख करोड़`;
    }
    return `₹ ${crores.toLocaleString('en-IN')} करोड़`;
  }

  if (lang === 'bn') {
    if (crores >= 100000) {
      const lakhCrores = (crores / 100000).toFixed(2);
      return `₹ ${lakhCrores} লক্ষ কোটি`;
    }
    return `₹ ${crores.toLocaleString('en-IN')} কোটি`;
  }

  if (lang === 'ta') {
    if (crores >= 100000) {
      const lakhCrores = (crores / 100000).toFixed(2);
      return `₹ ${lakhCrores} லட்சம் கோடி`;
    }
    return `₹ ${crores.toLocaleString('en-IN')} கோடி`;
  }

  if (lang === 'te') {
    if (crores >= 100000) {
      const lakhCrores = (crores / 100000).toFixed(2);
      return `₹ ${lakhCrores} లక్షల కోట్లు`;
    }
    return `₹ ${crores.toLocaleString('en-IN')} కోట్లు`;
  }

  if (lang === 'mr') {
    if (crores >= 100000) {
      const lakhCrores = (crores / 100000).toFixed(2);
      return `₹ ${lakhCrores} लाख कोटी`;
    }
    return `₹ ${crores.toLocaleString('en-IN')} कोटी`;
  }

  if (crores >= 100000) {
    const lakhCrores = (crores / 100000).toFixed(2);
    return `₹ ${lakhCrores} Lakh Cr`;
  }

  return `₹ ${crores.toLocaleString('en-IN')} Cr`;
}

/**
 * Key lookup with fallback hierarchy:
 * 1. Target Language
 * 2. Hindi (if target is not English)
 * 3. English (default)
 * 4. Fallback default parameter
 */
export function getTranslation(
  key: string,
  lang: LanguageCode = 'en',
  fallback?: string
): string {
  const langDict = TRANSLATIONS[lang];
  if (langDict && langDict[key]) {
    return langDict[key];
  }

  // Fallback to Hindi if another Indian language doesn't have the specific key yet
  if (lang !== 'hi' && lang !== 'en') {
    const hindiDict = TRANSLATIONS['hi'];
    if (hindiDict && hindiDict[key]) {
      return hindiDict[key];
    }
  }

  // Fallback to English
  const enDict = TRANSLATIONS['en'];
  if (enDict && enDict[key]) {
    return enDict[key];
  }

  return fallback !== undefined ? fallback : key;
}
